@dataclass(frozen=True)
class ScaleConfig:
    """Volumes and rates for one dataset scale."""

    name: str
    n_reviews: int
    n_survey_responses: int
    n_support_messages: int
    n_customers: int
    n_products: int
    n_surveys: int
    start_date: date = date(2026, 1, 1)
    end_date: date = date(2026, 10, 31)

    # Language mix: probability a customer with a non-English preference writes in it.
    native_language_use_prob: float = 0.40
    romanised_share: float = 0.5  # of non-English texts, share written in Latin script

    # Text phenomena
    sarcasm_rate: float = 0.10      # share of English NEGATIVE texts written sarcastically
    ambiguous_rate: float = 0.20    # share of NEUTRAL texts that are theme-free ambiguous statements
    suggestion_rate: float = 0.35   # share of NEUTRAL themed clauses that are suggestions
    theme_count_weights: tuple[float, float, float] = (0.60, 0.33, 0.07)  # 1, 2, 3 themes

    # Dataset split (stratified by source x sentiment)
    train_share: float = 0.70
    validation_share: float = 0.15  # test = remainder

    # Anomaly injection (applied AFTER valid baseline generation)
    anomaly_rates: dict[str, float] = field(default_factory=lambda: {
        "LABEL_CONTRADICTION": 0.010,  # of annotations
        "DUPLICATE_RESPONSE": 0.006,   # of survey responses
        "PRIVACY_LEAK": 0.004,         # of feedback records
        "INVALID_THEME": 0.006,        # of annotations
        "TARGET_LEAKAGE": 0.010,       # of test-split records
    })
    anomaly_min_count: int = 4
    explained_mismatch_rate: float = 0.004  # legit rating/text mismatches with an annotator note

    def to_dict(self) -> dict:
        d = asdict(self)
        d["start_date"] = self.start_date.isoformat()
        d["end_date"] = self.end_date.isoformat()
        return d


