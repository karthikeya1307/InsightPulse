@dataclass(frozen=True)
class ScenarioEvent:
    """A documented real-world-like disruption that shifts feedback in a window.

    While active, each generated record matching the scope is (with probability
    ``intensity``) forced to be NEGATIVE feedback about ``theme_code``. This is
    how sentiment shifts are planted - and they are recorded in
    ``scenario_events.json`` so trend detection can be evaluated against them.
    """

    event_code: str
    theme_code: str
    start: date
    end: date
    intensity: float
    description: str
    product_index: int | None = None  # 1-based index into the product catalogue
    category: str | None = None
    sources: tuple[str, ...] = ("SURVEY_RESPONSE", "REVIEW", "SUPPORT_MESSAGE")


