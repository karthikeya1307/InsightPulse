"""Business action items: evidence, status history and lifecycle updates."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402
import streamlit as st  # noqa: E402

import ui_kit as ui  # noqa: E402

TRANSITIONS = {"OPEN": ["IN_PROGRESS", "DISMISSED"], "IN_PROGRESS": ["BLOCKED", "RESOLVED", "OPEN"],
               "BLOCKED": ["IN_PROGRESS", "DISMISSED"], "RESOLVED": ["CLOSED", "IN_PROGRESS"],
               "CLOSED": [], "DISMISSED": []}

ui.page("Business Action Items", "Prioritised, rule-generated actions traceable to the feedback behind them.", "🧭")
f = st.columns(4)
status = f[0].selectbox("Status", ["All", "OPEN", "IN_PROGRESS", "BLOCKED", "RESOLVED", "CLOSED", "DISMISSED"])
priority = f[1].selectbox("Priority", ["All", "CRITICAL", "HIGH", "MEDIUM", "LOW"])
rule = f[2].selectbox("Rule", ["All", "NEGATIVE_THEME_CONCENTRATION", "RECURRING_COMPLAINT", "SENTIMENT_SHIFT", "MANUAL"])
active = f[3].toggle("Active only", value=False)
res = ui.get("/api/actions", {"status": None if status == "All" else status,
                              "priority": None if priority == "All" else priority,
                              "rule_code": None if rule == "All" else rule, "active_only": str(active).lower(),
                              "page_size": 200})
if res is None:
    st.stop()
items = pd.DataFrame(res["items"])
if items.empty:
    ui.empty("No actions match. Actions are generated by the pipeline 'actions' step.")
    st.stop()
k = st.columns(4)
ui.kpi(k[0], "Actions", ui.fmt_int(res["meta"]["total"]))
ui.kpi(k[1], "Critical", ui.fmt_int((items.priority == "CRITICAL").sum()))
ui.kpi(k[2], "Active", ui.fmt_int(items.status.isin(["OPEN", "IN_PROGRESS", "BLOCKED"]).sum()))
ui.kpi(k[3], "Evidence links", ui.fmt_int(items.evidence_count.sum()))
st.write("")
view = items.assign(priority=items.priority.map(ui.PRIORITY_ICON), product=items.product_name.fillna("All products"))
event = st.dataframe(view[["action_id", "priority", "status", "title", "product", "theme_name", "evidence_count",
                           "negative_share", "owner", "due_date", "rule_code"]],
                     hide_index=True, use_container_width=True, height=320, on_select="rerun",
                     selection_mode="single-row",
                     column_config={"negative_share": st.column_config.ProgressColumn("Neg. share", min_value=0, max_value=1, format="%.0f%%" if False else "%.2f")})
sel = event.selection.rows if event and event.selection else []
action_id = items.iloc[sel[0]].action_id if sel else st.selectbox("Open action", items.action_id)
a = ui.get(f"/api/actions/{action_id}", {"evidence_limit": 500})
if not a:
    st.stop()
st.markdown(f"### {a['action_id']} · {a['title']}")
st.markdown(f"<span class='ip-pill'>{ui.PRIORITY_ICON[a['priority']]}</span><span class='ip-pill'>{a['status']}</span>"
            f"<span class='ip-pill'>{a['theme_name']}</span><span class='ip-pill'>{a['product_name'] or 'All products'}</span>"
            f"<span class='ip-pill'>Owner: {a['owner']}</span><span class='ip-pill'>Due {a['due_date']}</span>",
            unsafe_allow_html=True)
st.write(a["description"])
st.markdown(f"**Recommended action:** {a['recommended_action']}")
left, right = st.columns([1.6, 1])
with left:
    st.markdown(f"**Supporting evidence** — {a['evidence_total']:,} feedback records (showing {len(a['evidence'])})")
    ev = pd.DataFrame(a["evidence"])
    if not ev.empty:
        st.dataframe(ev[["feedback_id", "feedback_date", "source_type", "sentiment_label", "text"]], hide_index=True,
                     use_container_width=True, height=300)
    with st.expander("Rule metrics"):
        st.json(a["metrics"])
with right:
    st.markdown("**Status history** (append-only events)")
    st.dataframe(pd.DataFrame(a["status_history"])[["from_status", "to_status", "changed_by", "note", "changed_at"]],
                 hide_index=True, use_container_width=True)
    options = TRANSITIONS[a["status"]]
    if options:
        with st.form("status"):
            new = st.selectbox("Move to", options)
            who = st.text_input("Changed by", value="analyst")
            note = st.text_area("Note", placeholder="Why is the status changing?")
            if st.form_submit_button("Update status", type="primary"):
                ok, body = ui.send("PATCH", f"/api/actions/{action_id}/status",
                                   {"status": new, "changed_by": who, "note": note or None})
                if ok:
                    st.success(f"{action_id} moved to {new}")
                    st.rerun()
                else:
                    st.error(body)
    else:
        st.caption(f"{a['status']} is a terminal state.")
